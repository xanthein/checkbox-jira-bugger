def _adf_node_text(node):
    """Recursively extract concatenated text from a single ADF node.

    `hardBreak` nodes (a "\n" embedded within a single paragraph) render
    as a single "\n" in Jira's own v2/string representation of the same
    content -- confirmed against a real issue (STELLA-4127) where a
    paragraph contains multiple `text` nodes separated by `hardBreak`
    nodes -- so they must be converted to "\n" here too, not dropped.
    """
    if not isinstance(node, dict):
        return ""
    if node.get("type") == "hardBreak":
        return "\n"
    parts = []
    if node.get("type") == "text":
        parts.append(node.get("text", "") or "")
    for child in node.get("content", None) or []:
        parts.append(_adf_node_text(child))
    return "".join(parts)


def description_to_plain_text(description):
    """Normalize a Jira issue `description` field to a plain text string.

    Jira Cloud can return `description` either as a plain string (REST API
    v2 / legacy compatibility mode) or as an Atlassian Document Format (ADF)
    dict (REST API v3, and observed in practice even with api_version=2
    pinned for some issues). Every description-parsing method in this file
    was written against the plain-string format, so this helper converts an
    ADF dict into an equivalent plain-text string (one line per top-level
    block, e.g. paragraph), while passing plain strings through unchanged
    and treating a missing description (None) as an empty string.
    """
    if description is None:
        return ""
    if isinstance(description, str):
        return description
    if isinstance(description, dict):
        blocks = [_adf_node_text(node) for node in description.get("content", None) or []]
        return "\n".join(blocks)
    return str(description)


def compose_jira_issue_dict(
        jira_project_key, issue_type, issue_summary, issue_description, issue_label, issue_priority="Medium",
        default_assignee=""):
    '''
    issue_type (string): "Theme", "Objective", "Epic", "Story", "Bug", "Sub-task"
    bug_priority (striing): "Highest", "High", "Medium", "Low", "Lowest"
    bug_label is a list!!
    '''
    issue_dict = {
        'project': {'key': jira_project_key},
        'summary': issue_summary,
        'description': issue_description,
        'issuetype': {'name': issue_type},
        'priority': {'name': issue_priority},
        'assignee': {'emailAddress': default_assignee},
        'labels': issue_label
    }
    return issue_dict



def deal_with_passed_test_cases_common_test(
        data, bugmgr: jira_api, submission_tarball, target_tag, manifest_name, manifest_version, bios_version,
        sku_number, sku_name):
    ''' deal with passed test cases
    '''
    """
    if logging.getLogger().getEffectiveLevel() == logging.DEBUG:
        logging.debug("=== Passed item list ===")
        logging.debug("===" * 20 )
        for item in data['results']:
            if item['status'] == 'pass' or item['status'] == 'skip':
                logging.debug('{}'.format(item['id']))
        logging.debug("===" * 20 )
    """
    logging.info("deal_with_passed_test_cases_common_test")
    for item in data['results']:
        if item['status'] == 'pass' or item['status'] == 'skip':
            logging.debug("checking pass: {}".format(item['id']))
            btlist = bugmgr.search_bug(item['id'])
            if len(btlist) > 0:
                for i in btlist:
                    logging.info('bug[%s][%s] %s: exist (pass_check)' % (i['key'], target_tag, i['fields']['summary']))

                # deal with first bug so far
                original_mv = bugmgr.get_bug_manifest_version(btlist[0])
                original_mn = bugmgr.get_bug_manifest_name(btlist[0])

                manifest_changed_msg = ''
                if original_mn != manifest_name:
                    manifest_changed_msg = 'manifest changed! %s -> %s' % (original_mn, manifest_name)

                if item['status'] == 'pass':
                    bugmgr.attach_file_to_bug(bugmgr.bugs_need_fixing_key, 'Auto attach', submission_tarball)
                    attach_comment_msg = bugmgr.compose_attaching_comment(
                        bugmgr.bugs_need_fixing_key, submission_tarball)

                    logging.info('Test passed - bug %s: %s' % (btlist[0]['key'], btlist[0]['fields']['summary']))
                    if item['id'] == 'miscellanea/cvescan':
                        bugmgr.comment_bug(btlist[0], 'The test passed on sku:%s with manifest:%s %s.\
                                            \nPlease check the difference then update bug status.\n%s\n%s\nsubmission: %s\n' % (sku_name,
                                           manifest_name, manifest_version, manifest_changed_msg, item['cve_append_message'], attach_comment_msg))
                    else:
                        bugmgr.comment_bug(btlist[0], 'The test passed on sku:%s with manifest:%s %s.\
                                \nPlease check the difference then update bug status.\n%s\nsubmission: %s\n' %
                                           (sku_name, manifest_name, manifest_version, manifest_changed_msg, attach_comment_msg))

                elif item['status'] == 'skip':
                    bugmgr.attach_file_to_bug(bugmgr.bugs_need_fixing_key, 'Auto attach', submission_tarball)
                    attach_comment_msg = bugmgr.compose_attaching_comment(
                        bugmgr.bugs_need_fixing_key, submission_tarball)
                    logging.info('Test skipped - bug %s: %s' % (btlist[0]['key'], btlist[0]['fields']['summary']))
                    bugmgr.comment_bug(btlist[0], 'The test skipped on sku:%s with manifest:%s %s.\
                            \nPlease check the difference then update bug status.\n%s\nsubmission: %s' %
                                       (sku_name, manifest_name, manifest_version, manifest_changed_msg, attach_comment_msg))


def deal_with_failed_test_cases_common_test(
        data, bugmgr: jira_api, submission_tarball, target_tag, manifest_name, manifest_version, bios_version,
        sku_number, sku_name, assignee, tester,
        rerun_on_fail=False, device_info=None, dut_ssh_config=None):
    '''deal with failed test cases

    If rerun_on_fail is True, device_info and dut_ssh_config must both be
    provided (non-None) by the caller; this function does not validate that
    precondition itself.
    '''
    if logging.getLogger().getEffectiveLevel() == logging.DEBUG:
        logging.debug("=== Failed item list ===")
        logging.debug("===" * 20)
        for item in data['results']:
            if item['status'] == 'fail':
                logging.debug('{}'.format(item['id']))
        logging.debug("===" * 20)

    logging.info('deal with failed test cases')
    for item in data['results']:
        logging.debug('check item {}'.format(item['id']))
        if item['status'] == 'fail':
            if rerun_on_fail:
                try:
                    eligible = is_job_eligible_for_rerun(item['full_id'], dut_ssh_config.rerun_job_patterns)
                    rerun_result = rerun_job(item['full_id'], device_info.ip_address, dut_ssh_config) if eligible else None
                except Exception as exc:
                    logging.warning(
                        "Unexpected error during rerun of %s: %s; proceeding with original result",
                        item['full_id'], exc)
                    rerun_result = None

                if rerun_result is None:
                    pass
                elif rerun_result.error:
                    logging.warning("Rerun failed for %s: %s; proceeding with original result",
                                     item['full_id'], rerun_result.error)
                elif rerun_result.status == 'pass':
                    logging.info("%s passed on rerun, skipping bug filing", item['full_id'])
                    continue
                else:
                    item = {**item, 'io_log': rerun_result.io_log, 'status': rerun_result.status}

            btlist = bugmgr.search_bug(item['id'])
            if len(btlist) > 0:
                for i in btlist:
                    logging.info('bug[%s][%s] %s: exist (fail_check)' % (i['key'], target_tag, i['fields']['summary']))

                # deal with first bug so far (human also file bug with same bug id)
                original_mv = bugmgr.get_bug_manifest_version(btlist[0])
                original_mn = bugmgr.get_bug_manifest_name(btlist[0])

                # if same manifest/sku don't comment/attach log
                if original_mv == manifest_version and original_mn == manifest_name and sku_name in bugmgr.get_bug_skus(
                        btlist[0]):
                    logging.info('identical test result on same test environment: %s %s %s' %
                                 (manifest_name, manifest_version, sku_name))
                    logging.debug("cyrus debug " + btlist[0]['fields']['status']['name'])
                    logging.debug("cyrus debug " + btlist[0]['fields']['parent']['key'])

                    if btlist[0]['fields']['status']['name'] in ['Done', 'In Review']:
                        logging.info('reopen bug %s: %s' % (btlist[0]['key'], btlist[0]['fields']['summary']))
                        bugmgr.reopen_bug(btlist[0])
                        bugmgr.comment_bug(btlist[0], 'Correct the bug status by bot')

                # original_mv != manifest_version or original_mn != manifest_name or sku_name not in bug description
                else:
                    manifest_changed_msg = ''
                    if original_mn != manifest_name:
                        manifest_changed_msg = 'manifest changed! %s -> %s' % (original_mn, manifest_name)

                    bugmgr.attach_file_to_bug(bugmgr.bugs_need_fixing_key, 'Auto attach', submission_tarball)
                    attach_comment_msg = bugmgr.compose_attaching_comment(
                        bugmgr.bugs_need_fixing_key, submission_tarball)
                    if item['id'] == 'miscellanea/cvescan':
                        bugmgr.comment_bug(btlist[0], 'The test case failed on sku:%s with manifest:%s %s.\n%s\n%s\n%s' % (
                            sku_name, manifest_name, manifest_version, manifest_changed_msg,
                            item['cve_append_message'], attach_comment_msg))
                    else:
                        bugmgr.comment_bug(btlist[0], 'The test case failed on sku:%s with manifest:%s %s.\n%s\n%s' % (
                            sku_name, manifest_name, manifest_version, manifest_changed_msg, attach_comment_msg))

                    if btlist[0]['fields']['status']['name'] in ['Done', 'In Review']:
                        bugmgr.reopen_bug(btlist[0])
                        logging.info('reopen bug %s: %s' % (btlist[0]['key'], btlist[0]['fields']['summary']))

                    if sku_name not in bugmgr.get_bug_skus(btlist[0]):
                        bugmgr.append_sku_to_bug_description(btlist[0], sku_name)

            # File a new bug
            else:
                bug_title, bug_description = format_bug(manifest_name,
                                                        manifest_version,
                                                        item['id'],
                                                        item['certification_status'],
                                                        restrict_log_msg(item['io_log']),
                                                        item['full_id'],
                                                        bios_version,
                                                        sku_number,
                                                        sku_name,
                                                        tester)
                bug_importance = BUG_PRIORITY_MAPPING[setting_bug_importance(item, bugmgr.projectname)]

                # Add SKU's name in bug title
                # remove the last number in  sku_name, like 'Thor3-AMD-1_202308-32003' to 'Thor2-AMD'
                if is_valid_sku_name(sku_name) and bugmgr.projectname == "sutton":
                    logging.debug("Attaching sku name to bug title for %s %s" % (bugmgr.projectname, sku_name))
                    if '_' in sku_name:
                        new_sku_name = '_'.join(sku_name.split('_')[:-1])
                    if '-' in new_sku_name:
                        new_sku_name = '-'.join(new_sku_name.split('-')[:-1])
                    bug_title_more = "Sanity," + new_sku_name
                    bug_title = bug_title.replace("Sanity", bug_title_more)
                    logging.debug("BUG title: %s" % bug_title)

                bugmgr.create_newbug(bug_title, bug_description, assignee, bug_importance, submission_tarball)


