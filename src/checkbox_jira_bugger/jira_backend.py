    def initial_epic_milestone_fixed_bugs(self, milestone):
        """
        Create jira epic "$milestone fixed bugs"
        return: jira epic key
        """
        if milestone is None:
            logging.debug("milestone is None")
            return None
        target_milestone = milestone.upper()
        milestone_reg = re.compile(r'(^M|^m)[\d]{1,2}|(^P|^p)[\d]{1,2}|(^RC|^rc)[\d]{1,2}')
        if not milestone_reg.fullmatch(target_milestone):
            logging.warning("Incorrect milestone naming %s" % target_milestone)
            return None

        resultkey = None
        issue_summary = JIRA_EPIC_M_FIXED_BUGS_SUMMARY.format(milestone=target_milestone)
        issue_description = JIRA_EPIC_M_FIXED_BUGS_DESCRIPTION.format(milestone=target_milestone)
        epics = self.search_epic(issue_summary)
        if len(epics) > 0:
            logging.debug("Milestone %s fixed bug epic already exist! %s" % (target_milestone, epics[0]['key']))
            resultkey = epics[0]['key']
        else:
            issue_dict = compose_jira_issue_dict(self.jira_project_key, "Epic",
                                                 issue_summary, issue_description, self.tag_list, "Medium", "")
            new_epic_key = self.create_jira_issue(issue_dict)['key']
            logging.debug("Create new jira epic for milestone %s fixed bugs: %s" % (target_milestone, new_epic_key))
            resultkey = new_epic_key

        # Maybe have M2, M3,... or RC2, RC3,...?
        if target_milestone == "M1":
            self.add_issue_as_child_issue(self.m1_release_objevtive, resultkey)
        elif target_milestone == "RC1":
            self.add_issue_as_child_issue(self.rc1_release_objevtive, resultkey)
        else:
            self.add_issue_as_child_issue(self.platform_development_key, resultkey)

        return resultkey

