class jira_rest_api:
    """
    """

    def __init__(self, jira_secrets_ini, project_key):
        self.email, self.apitoken = bh_get_jira_account_info(jira_secrets_ini)
        self.auth = HTTPBasicAuth(self.email, self.apitoken)
        self.project_key = project_key

    def rest_create_epic_issue(self, platform_tag, tag_list):
        # TODO error handling
        headers = {
            "Accept": "application/json",
            "Content-Type": "application/json"
        }

        new_jira_epic_issue = {
            "fields": {
                "project": {"key": self.project_key},
                "summary": JIRA_INITIAL_TICKET_SUMMARY.format(platform_tag=platform_tag),
                "description": JIRA_INITIAL_TICKET_DESCRIPTION,
                "labels": tag_list,
                "issuetype": {"name": "Epic"}}}

        response = requests.request(
            "POST",
            CANONICAL_JIRA_URL + "/rest/api/2/issue",
            data=json.dumps(new_jira_epic_issue),
            headers=headers,
            auth=self.auth
        )
        # print(response.status_code)
        # print(json.dumps(json.loads(response.text), sort_keys=True, indent=4, separators=(",", ": ")))
        ret = response.json()
        if response.status_code == 201:
            return ret['key']
        else:
            logging.debug("Create Epic issue failed!")
            return None

    def rest_add_issue_to_epic(self, epic_key, issue_key_list):
        """
        Empty response is returned if operation was successful.
        """
        headers = {
            "Content-Type": "application/json",
            # "Authorization": "Bearer <access_token>"
        }
        update_epic = {
            "issues": issue_key_list
        }

        response = requests.request(
            "POST",
            CANONICAL_JIRA_URL + "/rest/agile/1.0/epic/{}/issue".format(epic_key),
            data=json.dumps(update_epic),
            headers=headers,
            auth=self.auth
        )
        logging.info("Added issue {} to epic {}".format(issue_key_list, epic_key))


